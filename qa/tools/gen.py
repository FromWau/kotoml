"""Turns qa/comment-scenarios/*.md into CommentScenariosTest, which runs every scenario and prints its output."""
import re, glob, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(os.path.dirname(ROOT), "core/src/commonTest/kotlin/com/fromwau/kotoml/CommentScenariosTest.kt")
SKIP = set(sys.argv[1:])  # ids whose edit does not compile; run as "uncompilable"

def kstr(text):
    out = []
    for ch in text:
        if ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "$": out.append("\\$")
        elif ch == "\n": out.append("\\n")
        elif ch == "\r": out.append("\\r")
        elif ch == "\t": out.append("\\t")
        elif ord(ch) < 0x20 or ch == "\ufeff": out.append("\\u%04x" % ord(ch))
        else: out.append(ch)
    return '"' + "".join(out) + '"'

def note_bytes(note):
    parts = re.findall(r"`([^`]*)`", note)
    return [p.encode().decode("unicode_escape").encode("latin-1").decode("utf-8") for p in parts]

# API slips in the agents' snippets, corrected without changing what each scenario does.
FIXES = {
    "R-017": [("tableOrNull!!.remove(", "tableOrNull!!.removeItem(")],
    "R-035": [('it["n"].getOrNull()?.longOrNull', 'it.getOrNull("n")?.longOrNull')],
    "R-066": [("k.name ==", "k ==")],
    "R-070": [("k.name ==", "k ==")],
    "S-058": [(".toInlineTable()", ".toInlineTable().assertSuccess()")],
}

scenarios = []
for path in sorted(glob.glob(os.path.join(ROOT, "comment-scenarios", "*.md"))):
    text = open(path, encoding="utf-8").read()
    for chunk in re.split(r"\n(?=### [RSC]-\d+)", text):
        m = re.match(r"### ([RSC]-\d+): (.*)", chunk)
        if not m: continue
        sid, title = m.group(1), m.group(2)
        header = chunk.split("```")[0]
        inp = re.search(r"```toml input\n(.*?)```", chunk, re.S).group(1)
        edit = re.search(r"```kotlin edit\n(.*?)\n```", chunk, re.S).group(1)
        exp = re.search(r"```toml expected\n(.*?)```", chunk, re.S).group(1)
        for old, new in FIXES.get(sid, []):
            assert old in edit, (sid, old)
            edit = edit.replace(old, new)
        version = "V1_1" if "version: 1.1" in header else "V1_0"
        notes = [l for l in header.splitlines() if l.startswith("note:")]
        if notes and len(note_bytes(notes[0])) >= 2:
            inp, exp = note_bytes(notes[0])[:2]
        else:
            if "CRLF" in header:
                inp, exp = inp.replace("\n", "\r\n"), exp.replace("\n", "\r\n")
            if "no final newline" in header:
                inp = inp.rstrip("\r\n")
            if "BOM" in header:
                inp, exp = "\ufeff" + inp, "\ufeff" + exp
        scenarios.append((sid, title, version, inp, edit, exp, "open:" in header))

lines = [
    "package com.fromwau.kotoml",
    "",
    "import com.fromwau.kern.result.Result",
    "import com.fromwau.kern.result.assertSuccess",
    "import kotlin.test.Test",
    "import kotlin.test.assertEquals",
    "",
    "// Generated by qa/tools/gen.py from qa/comment-scenarios; edit those, then run `python3 qa/tools/gen.py`.",
    "/** The comment scenarios QA wrote: firm ones print as expected; open ones, awaiting a ruling, are only reported. */",
    "class CommentScenariosTest {",
    "    private class Scenario(",
    "        val id: String,",
    "        val open: Boolean,",
    "        val version: TomlVersion,",
    "        val input: String,",
    "        val expected: String,",
    "        val edit: (TomlDocument) -> Unit,",
    "    )",
    "",
    "    @Test",
    "    fun `every firm scenario prints as expected and every scenario prints valid TOML`() {",
    "        val failures = mutableListOf<String>()",
    "        for (s in scenarios) {",
    "            val doc = TomlDocument.parse(s.input, s.version).assertSuccess()",
    "            s.edit(doc)",
    "            val actual = doc.toString()",
    "            val valid = TomlDocument.parse(actual, TomlVersion.V1_1) is Result.Success",
    "            val status = when {",
    "                !valid -> \"invalid-output\"",
    "                actual == s.expected -> \"pass\"",
    "                else -> \"differs\"",
    "            }",
    "            if (status != \"pass\") {",
    "                val openMark = if (s.open) \" open\" else \"\"",
    "                println(\"@@@ \" + s.id + \" \" + status + openMark + \"\\n\" + actual + \"\\n<<<expected>>>\\n\" + s.expected)",
    "            }",
    "            if (!valid || (status == \"differs\" && !s.open)) failures += s.id",
    "        }",
    "        assertEquals(emptyList(), failures)",
    "    }",
    "",
    "    private val scenarios = listOf(",
]
for sid, title, version, inp, edit, exp, is_open in scenarios:
    fn = "e" + sid.replace("-", "_")
    lines.append(f"        Scenario({kstr(sid)}, {str(is_open).lower()}, TomlVersion.{version}, {kstr(inp)}, {kstr(exp)}, ::{fn}),")
lines.append("    )")
for sid, title, version, inp, edit, exp, is_open in scenarios:
    fn = "e" + sid.replace("-", "_")
    lines.append("")
    lines.append(f"    private fun {fn}(doc: TomlDocument) {{")
    if sid in SKIP:
        lines.append(f"        error(\"uncompilable\")")
    else:
        for l in edit.splitlines(): lines.append("        " + l)
    lines.append("    }")
lines.append("}")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(len(scenarios), "scenarios ->", OUT)
